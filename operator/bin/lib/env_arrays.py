"""Project bootstrap's REQUIRED_ENV / OPTIONAL_ENV from the env-consumption contract.

Phase B Cut B — kill the duplicate. bootstrap.sh used to HARDCODE these arrays,
a second copy of facts that operator/contracts/env-consumption.yaml already
owns (the drift #1324 was). Here the arrays become a pure projection of the
contract:

    REQUIRED_ENV = { v : requirement==required and stage reaches the Machine }
    OPTIONAL_ENV = { v : requirement==optional and stage reaches the Machine }

"reaches the Machine" = the stages whose vars are part of the core boot the
bootstrap script checks: boot, agent, broker. Excluded:
  - provisioning-host / image-build : never in the Machine's runtime env.
  - mcp-subprocess (e.g. CLIO_*)     : per-connector subprocess creds, only
    present when that connector is bound; outside bootstrap's core-boot purview
    (this matches the pre-Phase-B hand-curated scope, which carried broker-stage
    GOOGLE_* but no mcp-subprocess CLIO_*).

The output is rendered to operator/templates/_env-arrays.generated.sh (committed,
CI-sync-checked) and sourced by bootstrap.sh. A malformed contract fails the
generator in CI — never customer-zero's live boot.
"""

from __future__ import annotations

from pathlib import Path

import yaml

# Stages whose vars are part of the Machine's core boot (what bootstrap checks).
MACHINE_STAGES: frozenset[str] = frozenset({"boot", "agent", "broker"})

_GENERATED_REL = "operator/templates/_env-arrays.generated.sh"


def load_contract(path: Path) -> dict:
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    vars_ = data.get("vars")
    if not isinstance(vars_, dict) or not vars_:
        raise ValueError(f"env-consumption contract {path} has no `vars` map")
    return vars_


def compute(vars_: dict) -> tuple[list[str], list[str]]:
    """Return (required, optional), each sorted, projected from the contract."""
    required: list[str] = []
    optional: list[str] = []
    for name, spec in vars_.items():
        if not isinstance(spec, dict):
            raise ValueError(f"{name}: contract entry is not a mapping")
        stage = spec.get("stage")
        requirement = spec.get("requirement")
        if stage not in MACHINE_STAGES:
            continue
        if requirement == "required":
            required.append(name)
        elif requirement == "optional":
            optional.append(name)
        else:
            raise ValueError(f"{name}: invalid requirement {requirement!r}")
    return sorted(required), sorted(optional)


def render(required: list[str], optional: list[str]) -> str:
    """Render the committed bash snippet bootstrap.sh sources."""

    def _array(name: str, items: list[str]) -> str:
        body = "\n".join(f"  {item}" for item in items)
        return f"{name}=(\n{body}\n)"

    return (
        "# ============================================================================\n"
        "# GENERATED by operator/bin/gen-env-arrays.py from\n"
        "# operator/contracts/env-consumption.yaml — the single source of truth.\n"
        "# DO NOT EDIT BY HAND. Regenerate:  python3 operator/bin/gen-env-arrays.py\n"
        "# CI asserts this file is in sync (operator/bin/tests/test_env_array_generation.py).\n"
        "#\n"
        "# REQUIRED_ENV = contract vars (requirement: required) whose stage reaches the\n"
        "# Machine (boot|agent|broker). OPTIONAL_ENV = likewise for requirement: optional.\n"
        "# ============================================================================\n"
        f"{_array('REQUIRED_ENV', required)}\n\n"
        f"{_array('OPTIONAL_ENV', optional)}\n"
    )


def render_from_contract(contract_path: Path) -> str:
    required, optional = compute(load_contract(contract_path))
    return render(required, optional)


def repo_root() -> Path:
    """ss-console repo root, anchored to THIS module's own location."""
    # operator/bin/lib/env_arrays.py -> parents[3] == repo root
    return Path(__file__).resolve().parents[3]


def contract_path(repo_root: Path) -> Path:
    return repo_root / "operator" / "contracts" / "env-consumption.yaml"


def generated_path(repo_root: Path) -> Path:
    return repo_root / _GENERATED_REL
